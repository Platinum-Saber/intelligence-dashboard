"""
Merge all labeled data sources into a single training dataset.

Sources (all optional — at least one must exist):
    data/labeled/synthetic_labeled.csv   — generated by generate_synthetic.py
    data/labeled/real_labeled.csv        — generated by auto_label.py

Output:
    data/training_dataset.csv            — shuffled, deduplicated, split-ready

Usage:
    python prepare_dataset.py
    python prepare_dataset.py --no-synthetic   # real data only
    python prepare_dataset.py --no-real        # synthetic only
"""

import argparse
import csv
import logging
import random
from collections import Counter
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
logger = logging.getLogger(__name__)

LABELED_DIR  = Path(__file__).parent / "data" / "labeled"
SYNTHETIC_CSV = LABELED_DIR / "synthetic_labeled.csv"
REAL_CSV      = LABELED_DIR / "real_labeled.csv"
OUT_CSV       = Path(__file__).parent / "data" / "training_dataset.csv"

VALID_LABELS = {"positive", "negative", "neutral"}


def load_csv(path: Path, required_cols: list[str]) -> list[dict]:
    rows = []
    with open(path, encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if all(row.get(c, "").strip() for c in required_cols):
                rows.append(row)
    return rows


def main(include_synthetic: bool = True, include_real: bool = True, seed: int = 42) -> None:
    all_rows: list[dict] = []

    if include_synthetic and SYNTHETIC_CSV.exists():
        rows = load_csv(SYNTHETIC_CSV, ["text", "label", "topic"])
        logger.info(f"Loaded {len(rows)} synthetic rows from {SYNTHETIC_CSV.name}")
        all_rows.extend(rows)
    elif include_synthetic:
        logger.warning(f"{SYNTHETIC_CSV} not found — run generate_synthetic.py first")

    if include_real and REAL_CSV.exists():
        rows = load_csv(REAL_CSV, ["text", "label", "topic"])
        logger.info(f"Loaded {len(rows)} real rows from {REAL_CSV.name}")
        all_rows.extend(rows)
    elif include_real:
        logger.warning(f"{REAL_CSV} not found — run fetch_news.py then auto_label.py first")

    if not all_rows:
        raise RuntimeError("No data loaded — ensure at least one source CSV exists")

    # Normalise and filter
    clean: list[dict] = []
    seen_texts: set[str] = set()
    for row in all_rows:
        text  = row.get("text", "").strip()
        label = row.get("label", "").strip().lower()
        topic = row.get("topic", "").strip().upper()
        if not text or label not in VALID_LABELS or not topic:
            continue
        # Deduplicate by first 100 chars of text
        key = text[:100].lower()
        if key in seen_texts:
            continue
        seen_texts.add(key)
        clean.append({"text": text, "label": label, "topic": topic, "source": row.get("source", "")})

    random.seed(seed)
    random.shuffle(clean)

    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_CSV, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["text", "label", "topic", "source"])
        writer.writeheader()
        writer.writerows(clean)

    dist    = Counter(r["label"] for r in clean)
    by_topic = Counter(r["topic"] for r in clean)
    sources  = Counter(r["source"] for r in clean)

    logger.info(f"Total rows written : {len(clean)}")
    logger.info(f"Label distribution : {dict(dist)}")
    logger.info(f"Topic distribution : {dict(by_topic)}")
    logger.info(f"Source breakdown   : {dict(sources)}")
    logger.info(f"Output             : {OUT_CSV}")

    # Suggest a simple 80/20 split index
    split = int(len(clean) * 0.8)
    logger.info(f"Suggested train/val split: first {split} rows / last {len(clean) - split} rows")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Merge labeled sources into a single training dataset")
    parser.add_argument("--no-synthetic", action="store_true", help="Exclude synthetic data")
    parser.add_argument("--no-real",      action="store_true", help="Exclude real fetched data")
    parser.add_argument("--seed",         type=int, default=42, help="Random seed for shuffle (default: 42)")
    args = parser.parse_args()
    main(
        include_synthetic=not args.no_synthetic,
        include_real=not args.no_real,
        seed=args.seed,
    )
